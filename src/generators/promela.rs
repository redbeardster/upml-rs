fn generate_message_types<W: Write>(writer: &mut W, state_machine: &StateMachine) -> Result<()> {
    writeln!(writer, "/* Message types (events) */")?;
    writeln!(writer, "mtype = {{")?;
    
    let events = state_machine.events();
    let mut event_list: Vec<_> = events.into_iter().collect();
    event_list.sort();
    
    for (i, event) in event_list.iter().enumerate() {
        if i == event_list.len() - 1 {
            writeln!(writer, "    {}", event)?;
        } else {
            writeln!(writer, "    {},", event)?;
        }
    }
    
    writeln!(writer, "}};")?;
    Ok(())
}

fn generate_state_enum<W: Write>(writer: &mut W, state_machine: &StateMachine) -> Result<()> {
    writeln!(writer, "/* State enumeration */")?;
    writeln!(writer, "mtype = {{")?;
    
    let states = state_machine.states(false);
    let mut state_list: Vec<_> = states.into_iter().collect();
    state_list.sort();
    
    for (i, state) in state_list.iter().enumerate() {
        if i == state_list.len() - 1 {
            writeln!(writer, "    state_{}", state)?;
        } else {
            writeln!(writer, "    state_{},", state)?;
        }
    }
    
    writeln!(writer, "}};")?;
    Ok(())
}

