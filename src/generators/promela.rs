use std::io::Write;
use crate::state_machine::StateMachine;
use crate::Result;

/// Generate Promela code for FSM (Finite State Machine)
pub fn generate_fsm<W: Write>(mut writer: W, state_machine: &StateMachine) -> Result<()> {
    writeln!(writer, "/*")?;
    writeln!(writer, " * Generated Promela FSM model for state machine: {}", state_machine.id)?;
    writeln!(writer, " * Generated by upml-rs")?;
    writeln!(writer, " */")?;
    writeln!(writer)?;

    // Generate message types (events)
    generate_message_types(&mut writer, state_machine)?;
    writeln!(writer)?;

    // Generate state enumeration
    generate_state_enum(&mut writer, state_machine)?;
    writeln!(writer)?;

    // Generate global variables
    generate_global_variables(&mut writer, state_machine)?;
    writeln!(writer)?;

    // Generate main process
    generate_main_process(&mut writer, state_machine)?;
    writeln!(writer)?;

    // Generate LTL properties if any
    generate_ltl_properties(&mut writer, state_machine)?;

    Ok(())
}

